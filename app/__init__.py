# config - plik konfiguracyjny aplikacji w tym .env, który przechowuje ustawienia środowiskowe i konfiguracje aplikacji.
# database - setup bazy danych, w tym połączenie z bazą danych i inicjalizacja sesji.
# main - główny punkt wejścia aplikacji, który uruchamia serwer i inicjalizuje wszystkie komponenty.
# security - moduł odpowiedzialny za bezpieczeństwo aplikacji, w tym uwierzytelnianie i autoryzację użytkowników.
# seed - moduł odpowiedzialny za wypełnianie bazy danych przykładowymi danymi.
